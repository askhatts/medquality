class Command(BaseCommand):
    help = 'Создаёт не назначенные курсы по коммуникации с пациентом и синему коду из материалов Google Drive.'

    @transaction.atomic
    def handle(self, *args, **options):
        created_courses = 0
        created_tests = 0

        for spec in COURSES:
            direction, _ = QualityDirection.objects.get_or_create(
                title=spec['direction'],
                defaults={'description': spec['direction_description'], 'active': True},
            )
            direction.description = spec['direction_description']
            direction.active = True
            direction.save(update_fields=['description', 'active'])

            course, created = Course.objects.get_or_create(
                title=spec['title'],
                defaults={
                    'direction': direction,
                    'description': spec['description'],
                    'active': True,
                },
            )
            created_courses += int(created)
            course.direction = direction
            course.description = spec['description']
            course.active = True
            course.save(update_fields=['direction', 'description', 'active'])

            for order, (title, kind, file_id) in enumerate(spec['materials'], 1):
                lesson, _ = Lesson.objects.get_or_create(course=course, title=title)
                lesson.category = 'LESSON'
                lesson.kind = kind
                lesson.order = order
                lesson.url = drive_url(file_id)
                lesson.file = ''
                lesson.save()

            test = course.tests.filter(is_current=True).first()
            if not test:
                test = Test.objects.create(course=course, version=1, is_current=True)
                created_tests += 1
            if not test.assignments.exists():
                test.questions.all().delete()
                Question.objects.bulk_create([
                    Question(
                        test=test,
                        text=text,
                        question_type='SINGLE',
                        options=answers,
                        correct_index=correct_index,
                        correct_indexes=[correct_index],
                        explanation=explanation,
                        points=1,
                        order=order,
                    )
                    for order, (text, answers, correct_index, explanation) in enumerate(spec['questions'], 1)
                ])
            test.title = f'Итоговый тест: {spec["title"]}'
            test.instructions = 'Выберите один правильный ответ. Порядок вариантов ответа меняется автоматически.'
            test.time_limit_minutes = 10
            test.status = 'PUBLISHED'
            test.save(update_fields=['title', 'instructions', 'time_limit_minutes', 'status'])

        # This command deliberately creates no Assignment objects.
        self.stdout.write(self.style.SUCCESS(
            f'Курсы готовы: создано курсов {created_courses}, тестов {created_tests}; назначения не создавались.'
        ))
