class Command(BaseCommand):
    help = 'Добавляет курс этики и открытый анонимный опрос. Не меняет историю обучения и не создаёт ответов.'

    @transaction.atomic
    def handle(self, *args, **options):
        direction, _ = QualityDirection.objects.get_or_create(
            title='Профессиональная этика и культура общения',
            defaults={'description': 'Профессиональное поведение, уважение к пациентам и коллегам, доверие и безопасность.'},
        )
        course, created = Course.objects.get_or_create(
            title='Кодекс этики ЦЯМиО',
            defaults={'direction': direction, 'description': 'Учебные материалы по Кодексу этики работников ЦЯМиО, редакция 2026 года. Уважительное общение, конфликт интересов, защита заявителей и культура безопасности.'},
        )
        Lesson.objects.get_or_create(
            course=course, url='https://drive.google.com/file/d/1otDAoVLo4p91FFBm0LQWJF6m_engmetZ/view',
            defaults={'title': 'Кодекс этики ЦЯМиО — презентация для сотрудников', 'kind': 'LINK', 'order': 1},
        )
        document, _ = InternalDocument.objects.get_or_create(
            external_url='https://drive.google.com/file/d/139oHNFUuSBLnuz0MxAjr41htPcd2jNYo/view',
            defaults={'title': 'Кодекс этики ЦЯМиО — учебная редакция 2026', 'version': '2026', 'direction': direction, 'document_type': 'POLICY'},
        )
        document.courses.add(course)
        test = course.tests.filter(is_current=True).first()
        if not test:
            version = (course.tests.order_by('-version').values_list('version', flat=True).first() or 0) + 1
            test = Test.objects.create(
                course=course, title='Итоговый тест: Кодекс этики ЦЯМиО',
                version=version, status='PUBLISHED', time_limit_minutes=10,
                instructions='10 вопросов, по одному правильному ответу. Порядок вариантов меняется при открытии теста.',
            )
            Question.objects.bulk_create([
                Question(test=test, text=text, options=answers, correct_index=correct,
                         correct_indexes=[correct], explanation=explanation, points=1, order=order)
                for order, (text, answers, correct, explanation) in enumerate(ETHICS_QUESTIONS, 1)
            ])
        campaign, opened = SurveyCampaign.objects.get_or_create(
            slug='staff-wellbeing-2026-11',
            defaults={
                'title': 'Профессиональное благополучие сотрудников ЦЯМиО',
                'opens_on': timezone.localdate(),
                'audience_size': Profile.objects.filter(user__is_active=True).exclude(role='ADMIN').count(),
            },
        )
        self.stdout.write(self.style.SUCCESS(
            f'Курс: {"создан" if created else "уже существует"}; вопросов: {test.questions.count()}. '
            f'Опрос: {"создан" if opened else "уже существует"}; анкет: {campaign.responses.count()}. '
            'История и существующие назначения сохранены.',
        ))
