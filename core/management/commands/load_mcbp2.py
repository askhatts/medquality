class Command(BaseCommand):
    help = 'Создаёт или обновляет курс МЦБП 2 по материалам Google Drive.'

    @transaction.atomic
    def handle(self, *args, **options):
        direction = QualityDirection.objects.filter(title='Безопасность пациента').first()
        if not direction:
            direction = QualityDirection.objects.create(
                title='Безопасность пациента',
                description='Практики безопасного оказания медицинской помощи.',
                active=True,
            )
        course = Course.objects.filter(title=COURSE_TITLE).first()
        created = course is None
        if not course:
            course = Course.objects.create(
                direction=direction,
                description='Безопасная передача устной и телефонной информации, критических результатов и перевод пациентов между подразделениями.',
                title=COURSE_TITLE,
                active=True,
            )
        course.direction = direction
        course.description = 'Безопасная передача устной и телефонной информации, критических результатов и перевод пациентов между подразделениями.'
        course.active = True
        course.save(update_fields=['direction', 'description', 'active'])

        for order, (title, url) in enumerate(MATERIALS, 1):
            lesson, _ = Lesson.objects.get_or_create(course=course, title=title)
            lesson.category = 'LESSON'
            lesson.kind = 'VIDEO'
            lesson.order = order
            lesson.url = url
            lesson.file = ''
            lesson.save()

        test = Test.objects.filter(course=course, is_current=True).first()
        if test and test.assignments.exists():
            raise CommandError(
                'Текущая версия теста уже использована в назначениях. '
                'Для сохранения истории измените курс через редактор — он создаст новую версию.'
            )
        if not test:
            test = Test.objects.create(course=course, version=1, is_current=True)
        test.title = 'Итоговый тест: МЦБП 2'
        test.instructions = 'Выберите один правильный ответ. Варианты ответов перемешиваются автоматически.'
        test.time_limit_minutes = 10
        test.status = 'PUBLISHED'
        test.save()

        test.questions.all().delete()
        Question.objects.bulk_create([
            Question(
                test=test,
                text=text,
                question_type='SINGLE',
                options=answers,
                correct_index=correct,
                correct_indexes=[correct],
                points=1,
                order=order,
            )
            for order, (text, answers, correct) in enumerate(QUESTIONS, 1)
        ])

        verb = 'создан' if created else 'обновлён'
        self.stdout.write(self.style.SUCCESS(
            f'Курс «{COURSE_TITLE}» {verb}: 3 видео, 10 вопросов, лимит 10 минут.'
        ))
