class Command(BaseCommand):
    help = 'Создаёт два не назначенных курса по безопасности пациента из материалов Google Drive.'

    @transaction.atomic
    def handle(self, *args, **options):
        direction = QualityDirection.objects.filter(
            title='Безопасность пациента',
        ).order_by('id').first()
        if not direction:
            direction = QualityDirection.objects.create(
                title='Безопасность пациента',
                description='Безопасная маршрутизация, уход и защита прав пациентов.',
                active=True,
            )
        direction.active = True
        direction.save(update_fields=['active'])
        created_courses = created_tests = 0

        for spec in COURSES:
            course = Course.objects.filter(title=spec['title']).order_by('id').first()
            created = course is None
            if not course:
                course = Course.objects.create(
                    title=spec['title'],
                    direction=direction,
                    description=spec['description'],
                    active=True,
                )
            created_courses += int(created)
            course.direction = direction
            course.description = spec['description']
            course.active = True
            course.save(update_fields=['direction', 'description', 'active'])

            for order, (title, kind, file_id) in enumerate(spec['materials'], 1):
                material_url = drive_url(file_id)
                lesson = Lesson.objects.filter(course=course, url=material_url).first()
                if not lesson:
                    lesson = Lesson.objects.filter(course=course, order=order).first()
                if not lesson:
                    lesson = Lesson(course=course)
                lesson.title = title
                lesson.category = 'LESSON'
                lesson.kind = kind
                lesson.order = order
                lesson.url = material_url
                lesson.file = ''
                lesson.save()

            test = course.tests.filter(is_current=True).first()
            if not test:
                test = Test.objects.create(course=course, version=1, is_current=True)
                created_tests += 1
            if test.assignments.exists():
                if test.questions.count() != len(spec['questions']):
                    raise CommandError(f'Использованный тест курса «{course.title}» отличается от источника.')
            else:
                test.questions.all().delete()
                Question.objects.bulk_create([
                    Question(
                        test=test,
                        text=text,
                        question_type='SINGLE',
                        options=answers,
                        correct_index=correct_index,
                        correct_indexes=[correct_index],
                        explanation=explanation,
                        points=1,
                        order=order,
                    )
                    for order, (text, answers, correct_index, explanation)
                    in enumerate(spec['questions'], 1)
                ])
                test.title = f'Итоговый тест: {course.title}'
                test.instructions = 'Выберите один правильный ответ. Порядок вариантов ответа меняется автоматически.'
                test.time_limit_minutes = 10
                test.status = 'PUBLISHED'
                test.save(update_fields=['title', 'instructions', 'time_limit_minutes', 'status'])

        assignment_count = Assignment.objects.filter(course__title__in=[
            spec['title'] for spec in COURSES
        ]).count()
        self.stdout.write(self.style.SUCCESS(
            f'Курсы готовы: создано {created_courses}, тестов {created_tests}; '
            f'назначений по этим курсам: {assignment_count}.'
        ))
