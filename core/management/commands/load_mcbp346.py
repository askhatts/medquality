def drive_url(file_id):
    return f'https://drive.google.com/file/d/{file_id}/view'


class Command(BaseCommand):
    help = 'Создаёт МЦБП 3, 4 и 6 и историю завершения 2–4 марта 2026 года.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--with-history', action='store_true',
            help='Создать завершённые назначения всем активным сотрудникам, кроме sysadmin.',
        )

    @transaction.atomic
    def handle(self, *args, **options):
        direction = QualityDirection.objects.filter(title=DIRECTION_TITLE).first()
        if not direction:
            raise CommandError(f'Направление «{DIRECTION_TITLE}» не найдено.')

        employees = list(
            Profile.objects.select_related('user')
            .filter(user__is_active=True)
            .exclude(user__username='sysadmin')
            .order_by('user_id')
        )
        courses_created = tests_created = history_created = 0

        for spec in COURSES:
            course, created = Course.objects.get_or_create(
                title=spec['title'],
                defaults={'direction': direction, 'description': spec['description'], 'active': True},
            )
            courses_created += int(created)
            course.direction = direction
            course.description = spec['description']
            course.active = True
            course.save(update_fields=['direction', 'description', 'active'])

            for order, (title, kind, file_id) in enumerate(spec['materials'], 1):
                lesson, _ = Lesson.objects.get_or_create(course=course, title=title)
                lesson.category = 'LESSON'
                lesson.kind = kind
                lesson.order = order
                lesson.url = drive_url(file_id)
                lesson.file = ''
                lesson.save()
            test = Test.objects.filter(course=course, is_current=True).first()
            if not test:
                test = Test.objects.create(course=course, version=1, is_current=True)
                tests_created += 1
            if test.assignments.exists():
                if test.questions.count() != len(spec['questions']):
                    raise CommandError(
                        f'Тест «{test.title}» уже использован и отличается от источника; '
                        'история не изменена.'
                    )
            else:
                test.questions.all().delete()
                Question.objects.bulk_create([
                    Question(
                        test=test, text=text, question_type='SINGLE', options=answers,
                        correct_index=correct, correct_indexes=[correct], points=1, order=order,
                    )
                    for order, (text, answers, correct) in enumerate(spec['questions'], 1)
                ])
            test.title = f'Итоговый тест: МЦБП {spec["number"]}'
            test.instructions = 'Выберите один правильный ответ. Варианты ответов перемешиваются автоматически.'
            test.time_limit_minutes = 10
            test.status = 'PUBLISHED'
            test.save()

            if not options['with_history']:
                continue
            base_time = timezone.make_aware(datetime(*spec['completed_date'], 10, 0))
            question_count = len(spec['questions'])
            for employee_index, employee in enumerate(employees):
                score = (80, 90, 100)[(employee_index + spec['number']) % 3]
                completed_at = base_time + timedelta(minutes=employee_index % 480)
                key = f'mcbp{spec["number"]}-history-202603:{employee.user.username}'
                assignment, was_created = Assignment.objects.get_or_create(
                    demo_key=key,
                    defaults={
                        'user': employee.user, 'course': course, 'test_version': test,
                        'due_date': completed_at.date(), 'passing_score': 80,
                        'attempts_allowed': 1, 'status': 'COMPLETED',
                        'acknowledged_at': completed_at - timedelta(hours=1),
                        'completed_at': completed_at, 'is_demo': True,
                    },
                )
                if not was_created:
                    continue
                history_created += 1
                Assignment.objects.filter(pk=assignment.pk).update(
                    assigned_at=completed_at - timedelta(days=1)
                )
                correct_answers = round(question_count * score / 100)
                attempt = TestAttempt.objects.create(
                    assignment=assignment, number=1, correct_answers=correct_answers,
                    score=score, passed=True,
                    answers_snapshot=[{'historical_import': True, 'score': score}],
                )
                TestAttempt.objects.filter(pk=attempt.pk).update(completed_at=completed_at)

        self.stdout.write(self.style.SUCCESS(
            f'МЦБП 3, 4 и 6 готовы: создано курсов {courses_created}, тестов {tests_created}, '
            f'исторических завершений {history_created} для {len(employees)} сотрудников.'
        ))
