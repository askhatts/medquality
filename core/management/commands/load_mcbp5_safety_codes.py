class Command(BaseCommand):
    help = 'Создаёт МЦБП 5 и Красный, Жёлтый, Чёрный коды; при необходимости назначает их сотрудникам.'

    def add_arguments(self, parser):
        parser.add_argument('--assign', action='store_true', help='Назначить новые курсы всем активным сотрудникам, кроме sysadmin.')
        parser.add_argument('--due-date', default='2026-11-20', help='Срок в формате ГГГГ-ММ-ДД.')
        parser.add_argument('--due-time', default='23:59', help='Время окончания в формате ЧЧ:ММ.')
        parser.add_argument('--actor', default='sysadmin', help='Логин для записи операции в журнал действий.')

    @transaction.atomic
    def handle(self, *args, **options):
        try:
            due_date = date.fromisoformat(options['due_date'])
            due_time = datetime.strptime(options['due_time'], '%H:%M').time()
        except ValueError as exc:
            raise CommandError('Используйте дату ГГГГ-ММ-ДД и время ЧЧ:ММ.') from exc

        actor = User.objects.filter(username=options['actor']).first()
        profiles = list(
            Profile.objects.select_related('user')
            .filter(user__is_active=True)
            .exclude(user__username='sysadmin')
            .order_by('user_id')
        )
        created_courses = created_tests = created_assignments = updated_assignments = 0

        for spec in COURSES:
            direction, _ = QualityDirection.objects.get_or_create(
                title=spec['direction'],
                defaults={'description': spec['direction_description'], 'active': True},
            )
            direction.description = spec['direction_description']
            direction.active = True
            direction.save(update_fields=['description', 'active'])

            course, created = Course.objects.get_or_create(
                title=spec['title'],
                defaults={'direction': direction, 'description': spec['description'], 'active': True},
            )
            created_courses += int(created)
            course.direction = direction
            course.description = spec['description']
            course.active = True
            course.save(update_fields=['direction', 'description', 'active'])

            for order, (title, kind, file_id) in enumerate(spec['materials'], 1):
                material_url = drive_url(file_id)
                lesson = Lesson.objects.filter(course=course, url=material_url).first()
                if not lesson:
                    lesson = Lesson.objects.filter(course=course, order=order).first()
                if not lesson:
                    lesson = Lesson(course=course)
                lesson.title = title
                lesson.category = 'LESSON'
                lesson.kind = kind
                lesson.order = order
                lesson.url = material_url
                lesson.file = ''
                lesson.save()

            test = course.tests.filter(is_current=True).first()
            if not test:
                test = Test.objects.create(course=course, version=1, is_current=True)
                created_tests += 1
            if test.assignments.exists():
                if test.questions.count() != len(spec['questions']):
                    raise CommandError(f'Использованный тест курса «{course.title}» отличается от источника.')
            else:
                test.questions.all().delete()
                Question.objects.bulk_create([
                    Question(
                        test=test, text=text, question_type='SINGLE', options=answers,
                        correct_index=correct, correct_indexes=[correct], explanation=explanation,
                        points=1, order=order,
                    )
                    for order, (text, answers, correct, explanation) in enumerate(spec['questions'], 1)
                ])
                test.title = f'Итоговый тест: {course.title}'
                test.instructions = 'Выберите один правильный ответ. Порядок вариантов ответа меняется автоматически.'
                test.time_limit_minutes = 10
                test.status = 'PUBLISHED'
                test.save(update_fields=['title', 'instructions', 'time_limit_minutes', 'status'])

            if not options['assign']:
                continue
            for profile in profiles:
                latest = Assignment.objects.filter(
                    user=profile.user, course=course,
                ).order_by('-assigned_at', '-id').first()
                if latest and latest.status == 'COMPLETED':
                    continue
                attempts_used = latest.attempts.count() if latest else 0
                if latest and latest.status not in ('CANCELLED', 'REASSIGNED', 'FAILED') and attempts_used < latest.attempts_allowed and latest.test_version_id == test.id:
                    latest.due_date = due_date
                    latest.due_time = due_time
                    latest.passing_score = 80
                    latest.attempts_allowed = max(2, latest.attempts_allowed)
                    latest.status = 'IN_PROGRESS' if attempts_used else 'ASSIGNED'
                    latest.current_attempt_started_at = None
                    latest.save(update_fields=['due_date', 'due_time', 'passing_score', 'attempts_allowed', 'status', 'current_attempt_started_at'])
                    updated_assignments += 1
                    continue
                if latest and latest.status not in ('CANCELLED', 'REASSIGNED'):
                    latest.status = 'REASSIGNED'
                    latest.current_attempt_started_at = None
                    latest.save(update_fields=['status', 'current_attempt_started_at'])
                Assignment.objects.create(
                    user=profile.user, course=course, test_version=test,
                    due_date=due_date, due_time=due_time,
                    passing_score=80, attempts_allowed=2, status='ASSIGNED',
                )
                created_assignments += 1

        if actor and options['assign']:
            AuditLog.objects.create(
                user=actor, action='Добавлены и назначены новые курсы',
                object_label=f'МЦБП 5 и коды безопасности; срок {due_date:%d.%m.%Y} {due_time:%H:%M}',
            )
        self.stdout.write(self.style.SUCCESS(
            f'Курсы готовы: создано {created_courses}, тестов {created_tests}; '
            f'назначений создано {created_assignments}, обновлено {updated_assignments}.'
        ))
